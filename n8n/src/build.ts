import { build } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateWorkflows } from './validate.js';
import { ALL_WORKFLOWS } from './workflows.js';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '..', 'workflows');
const check = process.argv.includes('--check');

/** Bundles the shared adapters into a self-contained IIFE for the n8n Code node. */
export async function bundleCore(): Promise<string> {
  const result = await build({
    entryPoints: [join(here, 'core-entry.ts')],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'neutral',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    mainFields: ['module', 'main'],
    plugins: [
      {
        name: 'lite-job-schema',
        setup(b) {
          // Swap the zod-based job schema for a structural check (the Worker re-validates on ingest).
          b.onResolve({ filter: /schemas\/job\.js$/ }, (args) => (args.importer.includes('packages') ? { path: join(here, 'job-schema-lite.ts') } : undefined));
        },
      },
    ],
  });
  const code = result.outputFiles[0]!.text.trim();
  // A plain object receives the exports (see core-entry.ts for why getters are avoided).
  return `// ── @applypilot/core source adapters (generated by n8n/src/build.ts — do not edit here) ──\nconst __applypilot = {};\n${code}\nconst ApplyPilotCore = __applypilot;`;
}

const FILE_NAMES = [
  '00-command-dispatcher',
  '01-job-discovery',
  '02-resume-analysis',
  '03-job-matching',
  '04-application-preparation',
  '05-application-submission',
  '06-gmail-monitoring',
  '07-follow-up',
  '08-notifications-reports',
  '09-error-recovery',
];

async function main() {
  const bundle = await bundleCore();
  const workflows = ALL_WORKFLOWS(bundle);
  const problems = validateWorkflows(workflows);
  if (problems.length) {
    console.error('Workflow validation failed:\n- ' + problems.join('\n- '));
    process.exit(1);
  }
  mkdirSync(outDir, { recursive: true });
  let drift = 0;
  workflows.forEach((wf, i) => {
    const file = join(outDir, `${FILE_NAMES[i]}.json`);
    const json = `${JSON.stringify(wf, null, 2)}\n`;
    if (check) {
      if (!existsSync(file) || readFileSync(file, 'utf8') !== json) {
        console.error(`✗ ${FILE_NAMES[i]}.json is out of date — run "npm run n8n:build"`);
        drift++;
      }
    } else {
      writeFileSync(file, json);
      console.log(`✓ ${FILE_NAMES[i]}.json  (${wf.nodes.length} nodes)`);
    }
  });
  if (check && drift) process.exit(1);
  if (check) console.log(`✓ ${workflows.length} workflows valid and up to date (core bundle ${(bundle.length / 1024).toFixed(1)} KB)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
